import { createHash } from 'node:crypto';

const MAX_TEXT_LENGTH = 4_000;
const DEFAULT_TIMEOUT_MS = 30_000;
const SUPPORTED_VOICES = new Set(['Puck', 'Charon', 'Kore', 'Fenrir', 'Aoede']);

export class DesktopSpeechError extends Error {
  constructor(code, message, status = 400) {
    super(message);
    this.name = 'DesktopSpeechError';
    this.code = code;
    this.status = status;
  }
}

export function createDesktopSpeechService({
  apiKey,
  model = 'models/gemini-3.8-flash-lite-tts',
  fetchImpl = fetch,
  timeoutMs = DEFAULT_TIMEOUT_MS,
}) {
  if (typeof apiKey !== 'string' || !apiKey.trim() || /[\r\n]/.test(apiKey))
    throw new Error('DESKTOP_SPEECH_API_KEY_REQUIRED');

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/${model}:generateContent?key=${encodeURIComponent(apiKey.trim())}`;

  return {
    async synthesize(authContext, input, { signal } = {}) {
      if (!authContext?.userId)
        throw new DesktopSpeechError('UNAUTHENTICATED', 'Authentication required', 401);

      if (!input || typeof input !== 'object' || Array.isArray(input))
        throw new DesktopSpeechError('INVALID_INPUT', 'Expected JSON body with text');

      const rawText = typeof input.text === 'string' ? input.text.trim() : '';
      if (!rawText || rawText.length > MAX_TEXT_LENGTH)
        throw new DesktopSpeechError('INVALID_INPUT', `Text must be between 1 and ${MAX_TEXT_LENGTH} characters`);

      let voiceName = typeof input.voice === 'string' ? input.voice.trim() : 'Puck';
      if (!SUPPORTED_VOICES.has(voiceName)) {
        voiceName = 'Puck';
      }

      const body = {
        contents: [
          {
            parts: [{ text: rawText }],
          },
        ],
        generationConfig: {
          responseModalities: ['AUDIO'],
          speechConfig: {
            voiceConfig: {
              prebuiltVoiceConfig: {
                voiceName,
              },
            },
          },
        },
      };

      const requestSignal = signal
        ? AbortSignal.any([signal, AbortSignal.timeout(timeoutMs)])
        : AbortSignal.timeout(timeoutMs);

      let response;
      try {
        response = await fetchImpl(endpoint, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(body),
          signal: requestSignal,
        });
      } catch (err) {
        if (requestSignal.aborted)
          throw new DesktopSpeechError('SPEECH_TIMEOUT', 'Speech synthesis request timed out', 504);
        throw new DesktopSpeechError('SPEECH_FAILED', 'Could not reach speech service', 502);
      }

      if (!response.ok) {
        if (response.status === 429)
          throw new DesktopSpeechError('RATE_LIMITED', 'Speech synthesis is busy', 429);
        throw new DesktopSpeechError('SPEECH_FAILED', `Speech service error ${response.status}`, 502);
      }

      let data;
      try {
        data = await response.json();
      } catch {
        throw new DesktopSpeechError('SPEECH_INVALID', 'Invalid response from speech service', 502);
      }

      const candidate = data?.candidates?.[0];
      const inlineData = candidate?.content?.parts?.[0]?.inlineData;
      if (!inlineData || typeof inlineData.data !== 'string')
        throw new DesktopSpeechError('SPEECH_INVALID', 'No audio generated by speech model', 502);

      const mimeType = inlineData.mimeType || 'audio/wav';
      const audioBytes = Buffer.from(inlineData.data, 'base64');
      const sha256 = createHash('sha256').update(audioBytes).digest('hex');

      return {
        kind: 'synthesized_speech',
        text: rawText,
        audio: inlineData.data,
        mimeType,
        sha256,
        voice: voiceName,
        model,
      };
    },
  };
}
