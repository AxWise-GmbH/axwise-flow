/** Build a per-entity drill-down snapshot from a directory item (preview). */
export function demoSnapshotFor(entity, item) {
  const u = item.usage || {};
  const completed = item.counts?.goalsCompleted ?? 0;
  return {
    entity,
    entityId: item.id,
    range: { from: null, to: null },
    totals: {
      tokens: u.totalTokens || 0,
      promptTokens: u.inputTokens || 0,
      completionTokens: u.outputTokens || 0,
      cachedTokens: u.cachedTokens || 0,
      cost: u.cost || 0,
      calls: u.calls || 0,
      errorCalls: u.errorCalls || 0,
      errorRate: u.errorRate || 0,
      avgDurationMs: u.avgDurationMs || 0,
      p95DurationMs: Math.round((u.avgDurationMs || 0) * 2.3),
      evaluations: completed,
      approved: Math.round(completed * 0.85),
      avgScore: 7.6,
      revenue: 0,
      budgetUsd: item.budgetUsd || 0,
      spentUsd: item.spentUsd ?? u.cost ?? 0,
    },
    byModel: splitBreakdown(u, 'model'),
    byProvider: splitBreakdown(u, 'provider'),
    byAgent: [
      {
        agentId: item.id,
        agentName: item.name,
        tokens: u.totalTokens || 0,
        cost: u.cost || 0,
        calls: u.calls || 0,
      },
    ],
    timeseries: buildTimeseries(14, u.cost || 0, u.totalTokens || 0),
    meta: { source: 'demo' },
    source: 'demo',
  };
}
