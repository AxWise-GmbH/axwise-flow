const MIN = 60_000;

/** Deterministic daily series (no randomness) so the chart looks varied. */
function buildTimeseries(days, totalCost, totalTokens) {
  const out = [];
  const today = new Date();
  let weightSum = 0;
  const weights = [];
  for (let i = days - 1; i >= 0; i--) {
    const w = 0.55 + 0.45 * Math.abs(Math.sin(i / 2.7));
    weights.push(w);
    weightSum += w;
  }
  for (let idx = 0; idx < days; idx++) {
    const d = new Date(today);
    d.setDate(d.getDate() - (days - 1 - idx));
    const share = weights[idx] / weightSum;
    out.push({
      date: d.toISOString().slice(0, 10),
      cost: Number((totalCost * share).toFixed(2)),
      tokens: Math.round(totalTokens * share),
      calls: Math.round((totalTokens * share) / 2200),
    });
  }
  return out;
}

/** Split a usage rollup across a fixed model/provider mix for a breakdown. */
function splitBreakdown(usage, key) {
  const mix =
    key === 'model'
      ? [
          { provider: 'openai', model: 'gpt-4o', r: 0.42 },
          { provider: 'anthropic', model: 'claude-sonnet-5', r: 0.33 },
          { provider: 'groq', model: 'llama-3.3-70b-versatile', r: 0.25 },
        ]
      : [
          { provider: 'openai', r: 0.42 },
          { provider: 'anthropic', r: 0.33 },
          { provider: 'groq', r: 0.25 },
        ];
  return mix.map((m) => ({
    provider: m.provider,
    ...(m.model ? { model: m.model } : {}),
    tokens: Math.round((usage.totalTokens || 0) * m.r),
    cost: Number(((usage.cost || 0) * m.r).toFixed(4)),
    calls: Math.round((usage.calls || 0) * m.r),
  }));
}

