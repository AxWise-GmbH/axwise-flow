export const ATTEMPT_SCOPED_GOAL_DOCUMENT_CATEGORIES = Object.freeze([
  'goal-output',
  'goal-report',
  'goal-retrospective',
  'agent-report',
]);

const ATTEMPT_SCOPED_CATEGORIES = new Set(ATTEMPT_SCOPED_GOAL_DOCUMENT_CATEGORIES);

/** Return the durable identifiers for the goal's current execution attempt. */
export function goalDocumentAttempt(goal) {
  const authorization = goal?.data?.execution_authorization;
  const approval = goal?.data?.goal_approvals?.execution;
  const authorizationHash = String(authorization?.snapshot_hash || '').trim();
  const approvalHash = String(approval?.snapshot_hash || '').trim();
  const approvedSnapshotHash =
    authorization?.manifest?.valid === true &&
    authorization?.status === 'approved' &&
    approval?.status === 'approved' &&
    authorizationHash &&
    authorizationHash === approvalHash
      ? authorizationHash
      : null;

  return {
    decisionId: String(goal?.data?.axwise_orchestration?.decision_id || '').trim() || null,
    authorizationSnapshotHash: approvedSnapshotHash,
  };
}

/** Metadata stamped on artifacts generated by an execution attempt. */
export function goalDocumentAttemptMetadata(goal) {
  const attempt = goalDocumentAttempt(goal);
  return {
    ...(attempt.decisionId ? { axwise_decision_id: attempt.decisionId } : {}),
    ...(attempt.authorizationSnapshotHash
      ? { execution_authorization_snapshot_hash: attempt.authorizationSnapshotHash }
      : {}),
  };
}

function documentAttempt(document) {
  return {
    decisionId: String(document?.metadata?.axwise_decision_id || '').trim() || null,
    authorizationSnapshotHash:
      String(document?.metadata?.execution_authorization_snapshot_hash || '').trim() || null,
  };
}

function isAttemptScopedDocument(document) {
  return ATTEMPT_SCOPED_CATEGORIES.has(String(document?.category || '').trim());
}

/**
 * Keep execution-generated artifacts on the current goal attempt without
 * hiding foundational planning/context documents. Completed legacy goals keep
 * untagged historical artifacts readable; a live explicit attempt fails closed
 * immediately so an older output cannot flash before its replacement exists.
 */
export function currentGoalDocuments(goal, documents = []) {
  const rows = Array.isArray(documents) ? documents : [];
  const current = goalDocumentAttempt(goal);
  if (!current.decisionId && !current.authorizationSnapshotHash) return rows;

  const scopedRows = rows.filter(isAttemptScopedDocument);
  const hasTaggedScopedRows = scopedRows.some((document) => {
    const attempt = documentAttempt(document);
    return Boolean(attempt.decisionId || attempt.authorizationSnapshotHash);
  });
  if (!hasTaggedScopedRows) {
    // Preserve readable history for completed goals created before attempt
    // tagging shipped. A live/replanned goal with an explicit boundary must
    // hide ambiguous execution artifacts immediately instead of leaking the
    // previous attempt until its first replacement artifact is written.
    if (['completed', 'completed_with_warnings'].includes(String(goal?.status || ''))) {
      return rows;
    }
    return rows.filter((document) => !isAttemptScopedDocument(document));
  }

  return rows.filter((document) => {
    if (!isAttemptScopedDocument(document)) return true;
    const attempt = documentAttempt(document);
    if (current.decisionId && attempt.decisionId === current.decisionId) return true;
    if (
      current.authorizationSnapshotHash &&
      attempt.authorizationSnapshotHash === current.authorizationSnapshotHash
    ) {
      return true;
    }
    return false;
  });
}
