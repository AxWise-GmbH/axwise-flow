/**
 * NDA renderer — Vercel AI Gateway → Claude Sonnet writes a structured
 * mutual NDA in HTML using a Common-Paper / YC-style skeleton, then
 * uploads it to Supabase Storage and returns a `/api/render-deck` proxy
 * URL (re-using the existing HTML proxy that fixes Supabase's text/plain
 * content-type quirk).
 *
 * Why HTML not PDF: Pandoc can't run on Vercel functions (binary too
 * big), and adding `@react-pdf/renderer` introduces a heavy npm dep.
 * The HTML route reuses the deck-renderer infrastructure verbatim:
 * users print to PDF from the browser if they need a PDF copy.
 *
 * Why Common-Paper / YC skeleton: real legal templates exist as free
 * Markdown on GitHub. The LLM is given the structure as a prompt and
 * told to fill in party-specific fields. NOT a substitute for a
 * lawyer — every NDA includes a disclaimer.
 *
 * Cost: ~$0.05 per NDA (Claude Sonnet via gateway, ~3-5K tokens).
 * Time: ~10-15s wall time.
 */
import { executeLlmV2 } from '../concilium-handlers/llm-executor-v2.js';
import { executeLlmV2Tracked } from '../usage-handlers/tracked-llm.js';
import { buildSupabaseAdminClient } from '../../api/_lib/supabase-server.js';
import { createLogger } from '../../api/_lib/logger.js';

const log = createLogger('nda-renderer');

const NDA_SYSTEM_PROMPT = `You are a legal document drafter producing a complete HTML mutual non-disclosure agreement.

OUTPUT RULES (strict):
- Output ONLY valid HTML starting with <!DOCTYPE html>. No preamble. No markdown fences.
- Single self-contained file. ALL CSS inline in a <style> tag. Use a clean serif typeface (Cambria, Georgia, or system serif).
- Page-printable: 8.5x11 inches with 1in margins, 12pt body text, 1.5 line height.
- Structure with numbered sections (1. Definitions, 2. Confidential Information, 3. Obligations, etc.).
- Include a professional header with the agreement title and the parties section.
- Include numbered clauses, NOT bullet lists where avoidable — legal documents read sectionally.
- Include a signature block at the end with two signature lines, names printed, titles, and dates.
- ALWAYS include a footer disclaimer in 9pt italic gray text: "This is a template generated by AI. It is not a substitute for legal advice. Have a qualified attorney review before signing."

CONTENT REQUIREMENTS:
- This is a MUTUAL NDA — both parties exchange and protect confidential information.
- Standard sections: Definitions, Confidential Information, Obligations, Permitted Disclosures, Term and Termination, Return of Materials, Remedies, Governing Law, Entire Agreement, Signatures.
- Use the parties, jurisdiction, and term from the user's brief. If a field is missing, use a clearly-marked placeholder like <strong>[INSERT JURISDICTION]</strong>.
- Term defaults to 2 years if not specified.
- Governing law defaults to the jurisdiction of the disclosing party if not specified.
- Definitions section must define: "Confidential Information", "Disclosing Party", "Receiving Party", "Representatives".

QUALITY BAR: this should look like a deck-grade legal document, not a Word doc. Clean typography, real visual hierarchy, no PowerPoint colors. The reader should think "this looks like it came from a law firm" not "this looks like a template".`;

function buildNdaUserPrompt({ partyA, partyB, purpose, jurisdiction, termYears, additionalTerms }) {
  return `Generate a mutual NDA with these parameters:

Party A (Disclosing/Receiving): ${partyA || '[PARTY A NAME]'}
Party B (Disclosing/Receiving): ${partyB || '[PARTY B NAME]'}
Purpose / Project: ${purpose || '[PROJECT OR ENGAGEMENT DESCRIPTION]'}
Governing jurisdiction: ${jurisdiction || '[JURISDICTION]'}
Term: ${termYears || 2} years from the effective date
Additional terms: ${additionalTerms || '(none specified)'}

Today's date: ${new Date().toISOString().slice(0, 10)}

Now produce the complete HTML NDA.`;
}

/**
 * Generate an NDA HTML file and upload it to Supabase Storage.
 * @returns {Promise<{ htmlUrl, sizeBytes, htmlPreview }>}
 * @throws on any failure (caller falls back gracefully)
 */
export async function renderNdaViaHtml({ projectName, partyA, partyB, purpose, jurisdiction, termYears, additionalTerms }) {
  // 1. Generate HTML via Vercel AI Gateway → Claude Sonnet.
  //    Build the admin client up front (also reused for the Storage upload
  //    below) so the tracked executor can record one llm_usage row.
  const admin = buildSupabaseAdminClient();
  const llmResult = await executeLlmV2Tracked({
    provider: 'gateway',
    model: 'anthropic/claude-sonnet-4-6',
    temperature: 0.2, // legal docs need to be deterministic
    maxTokens: 6000,
    timeoutMs: 60000,
    systemPrompt: NDA_SYSTEM_PROMPT,
    prompt: buildNdaUserPrompt({ partyA, partyB, purpose, jurisdiction, termYears, additionalTerms }),
    usage: { admin, source: 'nda-render', operation: 'render' },
  });

  let html = (llmResult.content || '').trim();
  if (html.startsWith('```')) {
    html = html.replace(/^```(?:html)?/i, '').replace(/```$/, '').trim();
  }
  if (!html.toLowerCase().includes('<!doctype html')) {
    throw new Error('LLM did not produce a valid HTML document for NDA');
  }

  // 2. Upload to Supabase Storage (same bucket as decks, in the decks/
  //    folder so the existing /api/render-deck path-safety regex accepts it).
  //    `admin` was built above (and reused here) for the usage recording.
  const BUCKET = 'goal-deliverables';
  try {
    const { data: existing } = await admin.storage.getBucket(BUCKET);
    if (!existing) await admin.storage.createBucket(BUCKET, { public: true });
  } catch (bucketErr) {
    log.warn(null, 'nda-renderer.ensure-bucket.warn', { error: bucketErr.message });
  }

  const safeName = String(projectName)
    .toLowerCase()
    .replaceAll(/[^a-z0-9-]/g, '-')
    .replaceAll(/-+/g, '-')
    .replaceAll(/^-+|-+$/g, '')
    .slice(0, 60) || `nda-${Date.now().toString(36)}`;
  const storagePath = `decks/${safeName}-nda-${Date.now().toString(36)}.html`;

  const htmlBuffer = Buffer.from(html, 'utf-8');
  const { error: uploadErr } = await admin.storage.from(BUCKET).upload(storagePath, htmlBuffer, {
    contentType: 'text/html; charset=utf-8',
    upsert: false,
  });
  if (uploadErr) {
    throw new Error(`NDA upload failed: ${uploadErr.message}`);
  }

  // Return the /api/render-deck proxy URL (same as deck-renderer) so the
  // browser actually renders the HTML instead of seeing the text/plain
  // version that Supabase Storage forces.
  const baseUrl = process.env.VERCEL_URL
    ? `https://${process.env.VERCEL_URL}`
    : process.env.NEXT_PUBLIC_SITE_URL || 'https://orqaly.com';
  const htmlUrl = `${baseUrl}/api/render-deck?file=${encodeURIComponent(storagePath)}`;

  return {
    htmlUrl,
    storagePath,
    sizeBytes: htmlBuffer.length,
    htmlPreview: html.slice(0, 1500),
  };
}
