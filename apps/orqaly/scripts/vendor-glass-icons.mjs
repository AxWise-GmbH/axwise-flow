// One-off vendoring script for the Icons8 Liquid Glass icon pack.
// Reads .tsx icons from a cloned copy of icons8/liquid-glass-icons,
// strips TS types, replaces white gradient stops with currentColor so the
// icons can be tinted via CSS, and writes them as .jsx into
// src/components/icons/glass/. Also generates index.js with named exports.
//
// Run once after cloning the source repo. Safe to delete this script after.
// Usage: node scripts/vendor-glass-icons.mjs <path-to-cloned-liquid-glass-icons>
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');

const srcArg = process.argv[2] || '/tmp/glass-icons-vendor/liquid-glass-icons';
const SRC = path.join(srcArg, 'icons');
const DST = path.join(repoRoot, 'src/components/icons/glass');

if (!fs.existsSync(SRC)) {
  console.error(`Source not found: ${SRC}`);
  process.exit(1);
}

fs.mkdirSync(DST, { recursive: true });

const files = fs.readdirSync(SRC).filter((f) => f.endsWith('.tsx'));

function slugToPascal(slug) {
  return 'Lg' + slug.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

const exports = [];
let transformed = 0;
for (const f of files) {
  let src = fs.readFileSync(path.join(SRC, f), 'utf8');
  src = src.replace(/^import type \{ SVGProps \} from "react";\n/m, '');
  src = src.replace(
    /^import \{ Ref, forwardRef \} from "react";\n/m,
    'import { forwardRef } from "react";\n'
  );
  src = src.replace(
    /^interface SVGRProps \{\n  title\?: string;\n  titleId\?: string;\n\}\n/m,
    ''
  );
  src = src.replace(
    /\}: SVGProps<SVGSVGElement> & SVGRProps, ref: Ref<SVGSVGElement>\)/g,
    '}, ref)'
  );
  src = src.replace(/stopColor: "#fff"/g, 'stopColor: "currentColor"');

  const slug = f.replace(/\.tsx$/, '');
  const outName = slug + '.jsx';
  fs.writeFileSync(path.join(DST, outName), src);

  const exportName = slugToPascal(slug.toLowerCase());
  exports.push({ slug, exportName });
  transformed++;
}

const importLines = exports
  .map(({ slug, exportName }) => `export { default as ${exportName} } from './${slug}.jsx';`)
  .sort();
fs.writeFileSync(
  path.join(DST, 'index.js'),
  '// Auto-generated by scripts/vendor-glass-icons.mjs — see ../NOTICE.\n' +
    importLines.join('\n') +
    '\n'
);

console.log(`Transformed ${transformed} icons → ${DST}`);
console.log(`Wrote index.js with ${exports.length} exports.`);
